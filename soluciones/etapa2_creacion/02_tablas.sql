/* =====================================================================
   SOLUCION - 02 TABLAS (23)
   Ejecutar como: VETERINARIA
   ---------------------------------------------------------------------
   - PK con IDENTITY (Oracle 12c+): Oracle genera el ID solo, sin secuencia aparte.
   - Restricciones con nombre: PK_ FK_ UK_ CK_
   - Sin "ON DELETE" = NO ACTION (restringe el borrado del padre).
   - Nota SQL*Plus: no dejar lineas EN BLANCO dentro de un CREATE TABLE.
   Orden: catalogos -> personas -> mascotas -> agenda -> clinica -> inventario -> sistema
   ===================================================================== */


-- =====================================================================
-- CATALOGOS
-- =====================================================================
CREATE TABLE ESPECIE (
    ID_ESPECIE   NUMBER(5)     GENERATED ALWAYS AS IDENTITY,
    NOMBRE       VARCHAR2(40)  NOT NULL,
    CONSTRAINT PK_ESPECIE        PRIMARY KEY (ID_ESPECIE),
    CONSTRAINT UK_ESPECIE_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE RAZA (
    ID_RAZA      NUMBER(6)     GENERATED ALWAYS AS IDENTITY,
    ID_ESPECIE   NUMBER(5)     NOT NULL,
    NOMBRE       VARCHAR2(60)  NOT NULL,
    CONSTRAINT PK_RAZA           PRIMARY KEY (ID_RAZA),
    CONSTRAINT FK_RAZA_ESPECIE   FOREIGN KEY (ID_ESPECIE) REFERENCES ESPECIE (ID_ESPECIE),
    -- "Mestizo" puede existir en perro y en gato, pero no dos veces en la misma especie
    CONSTRAINT UK_RAZA_NOMBRE    UNIQUE (ID_ESPECIE, NOMBRE)
);

CREATE TABLE ESPECIALIDAD (
    ID_ESPECIALIDAD  NUMBER(4)     GENERATED ALWAYS AS IDENTITY,
    NOMBRE           VARCHAR2(60)  NOT NULL,
    CONSTRAINT PK_ESPECIALIDAD         PRIMARY KEY (ID_ESPECIALIDAD),
    CONSTRAINT UK_ESPECIALIDAD_NOMBRE  UNIQUE (NOMBRE)
);

CREATE TABLE CONSULTORIO (
    ID_CONSULTORIO  NUMBER(3)     GENERATED ALWAYS AS IDENTITY,
    NOMBRE          VARCHAR2(30)  NOT NULL,
    ACTIVO          CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_CONSULTORIO         PRIMARY KEY (ID_CONSULTORIO),
    CONSTRAINT UK_CONSULTORIO_NOMBRE  UNIQUE (NOMBRE),
    CONSTRAINT CK_CONSULTORIO_ACTIVO  CHECK (ACTIVO IN ('S', 'N'))
);

-- Catalogo de enfermedades. ID_ESPECIE NULL = aplica a todas las especies
CREATE TABLE DIAGNOSTICO (
    ID_DIAGNOSTICO  NUMBER(6)      GENERATED ALWAYS AS IDENTITY,
    CODIGO          VARCHAR2(10)   NOT NULL,
    NOMBRE          VARCHAR2(120)  NOT NULL,
    CATEGORIA       VARCHAR2(40)   NOT NULL,
    ID_ESPECIE      NUMBER(5),
    CONSTRAINT PK_DIAGNOSTICO          PRIMARY KEY (ID_DIAGNOSTICO),
    CONSTRAINT UK_DIAGNOSTICO_CODIGO   UNIQUE (CODIGO),
    CONSTRAINT FK_DIAGNOSTICO_ESPECIE  FOREIGN KEY (ID_ESPECIE) REFERENCES ESPECIE (ID_ESPECIE)
);

-- REFUERZO_DIAS NULL = dosis unica (no hay proxima dosis)
CREATE TABLE VACUNA (
    ID_VACUNA      NUMBER(5)     GENERATED ALWAYS AS IDENTITY,
    NOMBRE         VARCHAR2(80)  NOT NULL,
    ID_ESPECIE     NUMBER(5)     NOT NULL,
    REFUERZO_DIAS  NUMBER(4),
    CONSTRAINT PK_VACUNA          PRIMARY KEY (ID_VACUNA),
    CONSTRAINT FK_VACUNA_ESPECIE  FOREIGN KEY (ID_ESPECIE) REFERENCES ESPECIE (ID_ESPECIE),
    CONSTRAINT UK_VACUNA_NOMBRE   UNIQUE (NOMBRE, ID_ESPECIE),
    CONSTRAINT CK_VACUNA_REFUERZO CHECK (REFUERZO_DIAS > 0)
);


-- =====================================================================
-- PERSONAS
-- =====================================================================
CREATE TABLE PROPIETARIO (
    ID_PROPIETARIO  NUMBER(8)      GENERATED ALWAYS AS IDENTITY,
    DNI             VARCHAR2(12)   NOT NULL,
    NOMBRES         VARCHAR2(60)   NOT NULL,
    APELLIDOS       VARCHAR2(60)   NOT NULL,
    TELEFONO        VARCHAR2(15)   NOT NULL,
    EMAIL           VARCHAR2(100),
    DIRECCION       VARCHAR2(150),
    FECHA_REGISTRO  DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_PROPIETARIO        PRIMARY KEY (ID_PROPIETARIO),
    CONSTRAINT UK_PROPIETARIO_DNI    UNIQUE (DNI),
    -- DNI peruano = 8 digitos; carnet de extranjeria hasta 12
    CONSTRAINT CK_PROPIETARIO_DNI    CHECK (REGEXP_LIKE(DNI, '^[0-9]{8,12}$')),
    CONSTRAINT CK_PROPIETARIO_EMAIL  CHECK (EMAIL LIKE '%_@_%._%')
);

CREATE TABLE VETERINARIO (
    ID_VETERINARIO  NUMBER(5)      GENERATED ALWAYS AS IDENTITY,
    CMVP            VARCHAR2(10)   NOT NULL,
    NOMBRES         VARCHAR2(60)   NOT NULL,
    APELLIDOS       VARCHAR2(60)   NOT NULL,
    TELEFONO        VARCHAR2(15),
    EMAIL           VARCHAR2(100),
    ACTIVO          CHAR(1)        DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_VETERINARIO         PRIMARY KEY (ID_VETERINARIO),
    -- CMVP = numero de colegiatura del Colegio Medico Veterinario del Peru
    CONSTRAINT UK_VETERINARIO_CMVP    UNIQUE (CMVP),
    CONSTRAINT CK_VETERINARIO_ACTIVO  CHECK (ACTIVO IN ('S', 'N'))
);

-- Relacion N:M. Si se borra el veterinario, sus especialidades se van con el (CASCADE)
CREATE TABLE VETERINARIO_ESPECIALIDAD (
    ID_VETERINARIO   NUMBER(5)  NOT NULL,
    ID_ESPECIALIDAD  NUMBER(4)  NOT NULL,
    CONSTRAINT PK_VETERINARIO_ESPECIALIDAD PRIMARY KEY (ID_VETERINARIO, ID_ESPECIALIDAD),
    CONSTRAINT FK_VETESP_VETERINARIO  FOREIGN KEY (ID_VETERINARIO)  REFERENCES VETERINARIO (ID_VETERINARIO) ON DELETE CASCADE,
    CONSTRAINT FK_VETESP_ESPECIALIDAD FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES ESPECIALIDAD (ID_ESPECIALIDAD)
);

-- DIA_SEMANA: 1 = lunes ... 7 = domingo (ISO). Horas en texto 'HH24:MI' (se comparan como texto)
CREATE TABLE HORARIO_VETERINARIO (
    ID_HORARIO      NUMBER(6)    GENERATED ALWAYS AS IDENTITY,
    ID_VETERINARIO  NUMBER(5)    NOT NULL,
    DIA_SEMANA      NUMBER(1)    NOT NULL,
    HORA_INICIO     VARCHAR2(5)  NOT NULL,
    HORA_FIN        VARCHAR2(5)  NOT NULL,
    CONSTRAINT PK_HORARIO_VETERINARIO  PRIMARY KEY (ID_HORARIO),
    CONSTRAINT FK_HORARIO_VETERINARIO  FOREIGN KEY (ID_VETERINARIO) REFERENCES VETERINARIO (ID_VETERINARIO) ON DELETE CASCADE,
    CONSTRAINT UK_HORARIO              UNIQUE (ID_VETERINARIO, DIA_SEMANA, HORA_INICIO),
    CONSTRAINT CK_HORARIO_DIA          CHECK (DIA_SEMANA BETWEEN 1 AND 7),
    CONSTRAINT CK_HORARIO_INICIO       CHECK (REGEXP_LIKE(HORA_INICIO, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_HORARIO_FIN          CHECK (REGEXP_LIKE(HORA_FIN,    '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_HORARIO_RANGO        CHECK (HORA_FIN > HORA_INICIO)
);


-- =====================================================================
-- MASCOTAS (con relacion recursiva: padre y madre son otras mascotas)
-- =====================================================================
CREATE TABLE MASCOTA (
    ID_MASCOTA        NUMBER(8)     GENERATED ALWAYS AS IDENTITY,
    ID_PROPIETARIO    NUMBER(8)     NOT NULL,
    ID_RAZA           NUMBER(6)     NOT NULL,
    NOMBRE            VARCHAR2(40)  NOT NULL,
    SEXO              CHAR(1)       NOT NULL,
    FECHA_NACIMIENTO  DATE,
    COLOR             VARCHAR2(40),
    ESTERILIZADO      CHAR(1)       DEFAULT 'N' NOT NULL,
    ID_PADRE          NUMBER(8),
    ID_MADRE          NUMBER(8),
    ESTADO            VARCHAR2(10)  DEFAULT 'ACTIVO' NOT NULL,
    FECHA_REGISTRO    DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_MASCOTA              PRIMARY KEY (ID_MASCOTA),
    CONSTRAINT FK_MASCOTA_PROPIETARIO  FOREIGN KEY (ID_PROPIETARIO) REFERENCES PROPIETARIO (ID_PROPIETARIO),
    CONSTRAINT FK_MASCOTA_RAZA         FOREIGN KEY (ID_RAZA)        REFERENCES RAZA (ID_RAZA),
    -- SET NULL: si se borra el padre, el hijo sigue existiendo pero sin padre registrado
    CONSTRAINT FK_MASCOTA_PADRE        FOREIGN KEY (ID_PADRE) REFERENCES MASCOTA (ID_MASCOTA) ON DELETE SET NULL,
    CONSTRAINT FK_MASCOTA_MADRE        FOREIGN KEY (ID_MADRE) REFERENCES MASCOTA (ID_MASCOTA) ON DELETE SET NULL,
    CONSTRAINT CK_MASCOTA_SEXO         CHECK (SEXO IN ('M', 'H')),
    CONSTRAINT CK_MASCOTA_ESTERILIZADO CHECK (ESTERILIZADO IN ('S', 'N')),
    CONSTRAINT CK_MASCOTA_ESTADO       CHECK (ESTADO IN ('ACTIVO', 'FALLECIDO')),
    CONSTRAINT CK_MASCOTA_PADRES       CHECK (ID_PADRE <> ID_MASCOTA AND ID_MADRE <> ID_MASCOTA AND ID_PADRE <> ID_MADRE)
);


-- =====================================================================
-- AGENDA Y COLA
-- =====================================================================
-- Ciclo de vida: PROGRAMADA -> EN_ESPERA (llego + triaje) -> EN_ATENCION (llamada) -> ATENDIDA
--                PROGRAMADA -> CANCELADA | NO_ASISTIO
CREATE TABLE CITA (
    ID_CITA         NUMBER(10)     GENERATED ALWAYS AS IDENTITY,
    ID_MASCOTA      NUMBER(8)      NOT NULL,
    ID_VETERINARIO  NUMBER(5),
    FECHA_HORA      DATE           NOT NULL,
    DURACION_MIN    NUMBER(3)      DEFAULT 30 NOT NULL,
    ORIGEN          VARCHAR2(8)    DEFAULT 'AGENDADA' NOT NULL,
    MOTIVO          VARCHAR2(200)  NOT NULL,
    ESTADO          VARCHAR2(11)   DEFAULT 'PROGRAMADA' NOT NULL,
    FECHA_LLEGADA   DATE,
    FECHA_LLAMADO   DATE,
    ID_CONSULTORIO  NUMBER(3),
    FECHA_REGISTRO  DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CITA              PRIMARY KEY (ID_CITA),
    CONSTRAINT FK_CITA_MASCOTA      FOREIGN KEY (ID_MASCOTA)     REFERENCES MASCOTA (ID_MASCOTA),
    CONSTRAINT FK_CITA_VETERINARIO  FOREIGN KEY (ID_VETERINARIO) REFERENCES VETERINARIO (ID_VETERINARIO),
    CONSTRAINT FK_CITA_CONSULTORIO  FOREIGN KEY (ID_CONSULTORIO) REFERENCES CONSULTORIO (ID_CONSULTORIO),
    CONSTRAINT CK_CITA_DURACION     CHECK (DURACION_MIN BETWEEN 10 AND 240),
    CONSTRAINT CK_CITA_ORIGEN       CHECK (ORIGEN IN ('AGENDADA', 'SIN_CITA')),
    CONSTRAINT CK_CITA_ESTADO       CHECK (ESTADO IN ('PROGRAMADA', 'EN_ESPERA', 'EN_ATENCION', 'ATENDIDA', 'CANCELADA', 'NO_ASISTIO')),
    -- Una cita agendada siempre tiene veterinario; una "sin cita" lo recibe al ser llamada
    CONSTRAINT CK_CITA_VETERINARIO  CHECK (ORIGEN = 'SIN_CITA' OR ID_VETERINARIO IS NOT NULL),
    -- Coherencia entre el estado y los datos de la cola
    CONSTRAINT CK_CITA_COLA CHECK (
           (ESTADO IN ('PROGRAMADA', 'CANCELADA', 'NO_ASISTIO') AND FECHA_LLEGADA IS NULL AND ID_CONSULTORIO IS NULL)
        OR (ESTADO = 'EN_ESPERA' AND FECHA_LLEGADA IS NOT NULL AND ID_CONSULTORIO IS NULL)
        OR (ESTADO IN ('EN_ATENCION', 'ATENDIDA') AND FECHA_LLEGADA IS NOT NULL AND FECHA_LLAMADO IS NOT NULL
            AND ID_CONSULTORIO IS NOT NULL AND ID_VETERINARIO IS NOT NULL)
    ),
    CONSTRAINT CK_CITA_FECHAS       CHECK (FECHA_LLAMADO >= FECHA_LLEGADA)
);

-- Triaje: signos vitales + nivel de urgencia (escala Manchester: 1 = emergencia ... 5 = no urgente)
CREATE TABLE TRIAJE (
    ID_TRIAJE          NUMBER(10)     GENERATED ALWAYS AS IDENTITY,
    ID_CITA            NUMBER(10)     NOT NULL,
    FECHA              DATE           DEFAULT SYSDATE NOT NULL,
    PESO_KG            NUMBER(5,2)    NOT NULL,
    TEMPERATURA        NUMBER(3,1)    NOT NULL,
    FREC_CARDIACA      NUMBER(3),
    FREC_RESPIRATORIA  NUMBER(3),
    NIVEL_URGENCIA     NUMBER(1)      NOT NULL,
    OBSERVACIONES      VARCHAR2(300),
    CONSTRAINT PK_TRIAJE              PRIMARY KEY (ID_TRIAJE),
    -- 1:1 con CITA (UNIQUE en la FK) y CASCADE: el triaje no existe sin su cita
    CONSTRAINT UK_TRIAJE_CITA         UNIQUE (ID_CITA),
    CONSTRAINT FK_TRIAJE_CITA         FOREIGN KEY (ID_CITA) REFERENCES CITA (ID_CITA) ON DELETE CASCADE,
    CONSTRAINT CK_TRIAJE_PESO         CHECK (PESO_KG > 0),
    CONSTRAINT CK_TRIAJE_TEMPERATURA  CHECK (TEMPERATURA BETWEEN 30 AND 45),
    CONSTRAINT CK_TRIAJE_FC           CHECK (FREC_CARDIACA BETWEEN 10 AND 400),
    CONSTRAINT CK_TRIAJE_FR           CHECK (FREC_RESPIRATORIA BETWEEN 1 AND 200),
    CONSTRAINT CK_TRIAJE_URGENCIA     CHECK (NIVEL_URGENCIA BETWEEN 1 AND 5)
);


