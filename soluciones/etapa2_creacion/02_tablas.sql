    CONSTRAINT PK_AUDITORIA            PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT CK_AUDITORIA_OPERACION  CHECK (OPERACION IN ('INSERT', 'UPDATE', 'DELETE'))
);

-- Las genera el job nocturno (PKG_ALERTAS). ID_REFERENCIA apunta a la vacunacion, medicamento o cita
CREATE TABLE ALERTA (
    ID_ALERTA      NUMBER(10)     GENERATED ALWAYS AS IDENTITY,
    TIPO           VARCHAR2(7)    NOT NULL,
    ID_REFERENCIA  NUMBER(10)     NOT NULL,
    MENSAJE        VARCHAR2(300)  NOT NULL,
    FECHA          DATE           DEFAULT SYSDATE NOT NULL,
    LEIDA          CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_ALERTA        PRIMARY KEY (ID_ALERTA),
    CONSTRAINT CK_ALERTA_TIPO   CHECK (TIPO IN ('VACUNA', 'STOCK', 'CITA')),
    CONSTRAINT CK_ALERTA_LEIDA  CHECK (LEIDA IN ('S', 'N'))
);


