-- PROXIMA_DOSIS la calcula el trigger TRG_VACUNACION (FECHA_APLICACION + REFUERZO_DIAS)
CREATE TABLE VACUNACION (
    ID_VACUNACION     NUMBER(10)    GENERATED ALWAYS AS IDENTITY,
    ID_MASCOTA        NUMBER(8)     NOT NULL,
    ID_VACUNA         NUMBER(5)     NOT NULL,
    ID_VETERINARIO    NUMBER(5)     NOT NULL,
    FECHA_APLICACION  DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
    PROXIMA_DOSIS     DATE,
    LOTE              VARCHAR2(20),
    CONSTRAINT PK_VACUNACION              PRIMARY KEY (ID_VACUNACION),
    CONSTRAINT FK_VACUNACION_MASCOTA      FOREIGN KEY (ID_MASCOTA)     REFERENCES MASCOTA (ID_MASCOTA),
    CONSTRAINT FK_VACUNACION_VACUNA       FOREIGN KEY (ID_VACUNA)      REFERENCES VACUNA (ID_VACUNA),
    CONSTRAINT FK_VACUNACION_VETERINARIO  FOREIGN KEY (ID_VETERINARIO) REFERENCES VETERINARIO (ID_VETERINARIO),
    CONSTRAINT CK_VACUNACION_PROXIMA      CHECK (PROXIMA_DOSIS > FECHA_APLICACION)
);


-- =====================================================================
-- INVENTARIO DE INSUMOS (uso interno de la clinica, no es tienda)
-- =====================================================================
CREATE TABLE MEDICAMENTO (
    ID_MEDICAMENTO  NUMBER(6)     GENERATED ALWAYS AS IDENTITY,
    NOMBRE          VARCHAR2(80)  NOT NULL,
    PRESENTACION    VARCHAR2(60)  NOT NULL,
    UNIDAD          VARCHAR2(15)  NOT NULL,
    STOCK_ACTUAL    NUMBER(8,2)   DEFAULT 0 NOT NULL,
    STOCK_MINIMO    NUMBER(8,2)   DEFAULT 0 NOT NULL,
    ACTIVO          CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_MEDICAMENTO          PRIMARY KEY (ID_MEDICAMENTO),
    CONSTRAINT UK_MEDICAMENTO          UNIQUE (NOMBRE, PRESENTACION),
    -- Ultima barrera: aunque falle el trigger, el stock nunca queda negativo
    CONSTRAINT CK_MEDICAMENTO_STOCK    CHECK (STOCK_ACTUAL >= 0),
    CONSTRAINT CK_MEDICAMENTO_MINIMO   CHECK (STOCK_MINIMO >= 0),
    CONSTRAINT CK_MEDICAMENTO_ACTIVO   CHECK (ACTIVO IN ('S', 'N'))
);

-- Kardex: el stock NO se edita a mano; cada movimiento lo actualiza (trigger TRG_MOVIMIENTO_STOCK)
CREATE TABLE MOVIMIENTO_STOCK (
    ID_MOVIMIENTO   NUMBER(10)     GENERATED ALWAYS AS IDENTITY,
    ID_MEDICAMENTO  NUMBER(6)      NOT NULL,
    TIPO            VARCHAR2(7)    NOT NULL,
    CANTIDAD        NUMBER(8,2)    NOT NULL,
    FECHA           DATE           DEFAULT SYSDATE NOT NULL,
    ID_ATENCION     NUMBER(10),
    MOTIVO          VARCHAR2(150),
    CONSTRAINT PK_MOVIMIENTO_STOCK     PRIMARY KEY (ID_MOVIMIENTO),
    CONSTRAINT FK_MOVIMIENTO_MEDICAMENTO FOREIGN KEY (ID_MEDICAMENTO) REFERENCES MEDICAMENTO (ID_MEDICAMENTO),
    CONSTRAINT FK_MOVIMIENTO_ATENCION  FOREIGN KEY (ID_ATENCION) REFERENCES ATENCION (ID_ATENCION),
    CONSTRAINT CK_MOVIMIENTO_TIPO      CHECK (TIPO IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT CK_MOVIMIENTO_CANTIDAD  CHECK (CANTIDAD > 0),
    -- Solo una SALIDA puede venir de una atencion
    CONSTRAINT CK_MOVIMIENTO_ATENCION  CHECK (TIPO = 'SALIDA' OR ID_ATENCION IS NULL)
);


-- =====================================================================
-- SISTEMA: usuarios de la aplicacion, auditoria y alertas
-- =====================================================================
-- CLAVE_HASH = SHA-256 en hexadecimal (64 caracteres). Nunca se guarda la clave en texto plano.
CREATE TABLE USUARIO (
    ID_USUARIO       NUMBER(5)      GENERATED ALWAYS AS IDENTITY,
    USUARIO          VARCHAR2(30)   NOT NULL,
    CLAVE_HASH       VARCHAR2(64)   NOT NULL,
    NOMBRE_COMPLETO  VARCHAR2(100)  NOT NULL,
    ROL              VARCHAR2(11)   NOT NULL,
    ID_VETERINARIO   NUMBER(5),
    ACTIVO           CHAR(1)        DEFAULT 'S' NOT NULL,
    ULTIMO_ACCESO    DATE,
    CONSTRAINT PK_USUARIO              PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO              UNIQUE (USUARIO),
    -- Un veterinario tiene a lo mas una cuenta (UNIQUE ignora los NULL)
    CONSTRAINT UK_USUARIO_VETERINARIO  UNIQUE (ID_VETERINARIO),
    CONSTRAINT FK_USUARIO_VETERINARIO  FOREIGN KEY (ID_VETERINARIO) REFERENCES VETERINARIO (ID_VETERINARIO),
    CONSTRAINT CK_USUARIO_ROL          CHECK (ROL IN ('ADMIN', 'RECEPCION', 'VETERINARIO')),
    CONSTRAINT CK_USUARIO_ACTIVO       CHECK (ACTIVO IN ('S', 'N')),
    CONSTRAINT CK_USUARIO_FORMATO      CHECK (REGEXP_LIKE(USUARIO, '^[a-z][a-z0-9._]{2,29}$')),
    -- El rol VETERINARIO exige estar vinculado a un veterinario
    CONSTRAINT CK_USUARIO_VET          CHECK (ROL <> 'VETERINARIO' OR ID_VETERINARIO IS NOT NULL)
);

-- USUARIO_APP: la app envia el usuario logueado como "client identifier" de la sesion Oracle
CREATE TABLE AUDITORIA (
    ID_AUDITORIA  NUMBER(12)     GENERATED ALWAYS AS IDENTITY,
    TABLA         VARCHAR2(30)   NOT NULL,
    OPERACION     VARCHAR2(6)    NOT NULL,
    ID_REGISTRO   NUMBER(12)     NOT NULL,
    DETALLE       VARCHAR2(400),
    USUARIO_BD    VARCHAR2(128)  DEFAULT USER NOT NULL,
